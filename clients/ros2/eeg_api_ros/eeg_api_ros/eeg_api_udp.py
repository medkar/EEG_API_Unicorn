"""Connect a device to the EEG_API_Unicorn console over UDP, with the Python standard library
only (a Raspberry Pi, or any computer without LSL). Do not edit this file: the settings are in
config.json, and your application is the function that receives the decisions (see example.py).

    from eeg_api_udp import EegApiDevice, load_config

    device = EegApiDevice(load_config("config.json"))
    device.connect()                       # announces itself until the console connects it
    device.start()                         # sends the settings of config.json, starts the mode
    for decision in device.decisions():    # one dict per decision, channels by name
        ...                                # your application
    device.close()                         # stops the mode it started, says "bye"

The protocol follows docs/control.md, "Over the network (UDP)": one JSON object per datagram,
carrying "v": 1; the device announces itself every second (hello) until someone clicks
"Connect an application", picks it, then "Connect"; then it sends the same commands as over LSL
and receives the engine's replies, its status and its decisions (each with a growing "seq"). Both
sides send "alive" every second; 5 s of silence ends the connection. Only the console listens to
UDP (port 5010), not `server.py` alone. Modes served: ssvep, mi, neuro.
"""

import json
import socket
import time
import uuid

HELLO = "EEG_API_Unicorn"   # the word that tells the engine "this is a device for you"
VERSION = 1
HELLO_EVERY_S = 1.0
ALIVE_EVERY_S = 1.0
SILENCE_S = 5.0             # no news from the engine for this long: disconnected
REPLY_TIMEOUT_S = 2.0       # a command with no reply after this long is sent again...
TRIES = 3                   # ...at most this many times in all
MAX_DATAGRAM = 8192

DEFAULTS = {
    "app_name": "my-device",
    "device_id": "",
    "device_port": 5011,
    "engine_host": "255.255.255.255",
    "engine_port": 5010,
    "mode": "ssvep",
    "params": {},
    "propose_refresh_hz": 0,
    "stop_mode_on_exit": True,
}


def load_config(path):
    """The settings of config.json, completed with the defaults above."""
    with open(path, encoding="utf-8") as f:
        config = json.load(f)
    unknown = sorted(set(config) - set(DEFAULTS))
    if unknown:
        raise ValueError(f"{path}: unknown setting(s) {', '.join(unknown)}; "
                         f"known: {', '.join(DEFAULTS)}")
    return dict(DEFAULTS, **config)


def config_path(name="config.json"):
    """config.json next to the script that runs, whatever the current folder."""
    import __main__
    import os
    here = os.path.dirname(os.path.abspath(getattr(__main__, "__file__", "."))) or "."
    return os.path.join(here, name)


class EegApiError(Exception):
    """A step that did not get the expected reply. The message says which, and why."""


class EegApiDevice:
    """One UDP socket, and what the device knows about the engine that connected it."""

    def __init__(self, config, log=print, on_identify=None):
        self.config = dict(DEFAULTS, **config)
        self.log = log
        # "Identify" in the console: blink a LED, so that the person sees which device this is.
        self.on_identify = on_identify or (lambda: log("IDENTIFY: the console asks this "
                                                       "device to show itself"))
        mac = uuid.getnode()
        self.ident = self.config["device_id"] or f"{(mac >> 8) & 0xFF:02X}:{mac & 0xFF:02X}"
        self.name = self.config["app_name"]
        self.mode = self.config["mode"]
        self.sock = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
        self.sock.setsockopt(socket.SOL_SOCKET, socket.SO_BROADCAST, 1)
        # ONE socket, bound to the announced port, sends everything: the engine recognises the
        # device by the address its datagrams come FROM.
        self.sock.bind(("", int(self.config["device_port"])))
        self.port = self.sock.getsockname()[1]
        self.sock.settimeout(0.05)
        self.announce_to = (self.config["engine_host"], int(self.config["engine_port"]))
        self.engine = None          # (ip, port) of the engine that connected us
        self.console = None
        self.last_seq = 0
        self.heard = 0.0
        self.next_hello = self.next_alive = 0.0
        self.sent = 0
        self.replies, self.failures, self.queue = {}, {}, []
        self.phase = None
        self.ended = None           # the "disconnected" message, or "silent"
        self.started_here = False

    # --- the handshake ---------------------------------------------------------------------

    def connect(self, should_stop=lambda: False):
        """Announces the device every second, with no time limit, until a console connects it.
        Returns True once connected, False if should_stop() became true first."""
        self.log(f"Announcing '{self.name}' (id {self.ident}, UDP port {self.port}) to "
                 f"{self.announce_to[0]}:{self.announce_to[1]}: in the console, \"Connect an "
                 f"application\", pick '{self.name}', then \"Connect\".")
        self.ended = None
        while self.engine is None:
            if should_stop():
                return False
            self.poll()
        self.log(f"Connected by the console of '{self.console}'")
        return True

    def connected(self):
        return self.engine is not None

    def why_disconnected(self):
        if self.ended == "silent":
            return f"no news from the engine for {SILENCE_S:g} s"
        cause = (self.ended or {}).get("cause")
        if cause == "console":
            return "disconnected in the console"
        if cause == "engine_stopped":
            return "the engine stopped (the console closed)"
        return "disconnected"

    # --- commands ------------------------------------------------------------------------------

    def send_command(self, cmd, params=None):
        """Sends one command of docs/control.md for our mode and returns ITS reply (a dict),
        sending it again if UDP lost it. Raises EegApiError when disconnected or unanswered."""
        self.sent += 1
        command = {"cmd": cmd, "mode": self.mode, "ref": f"{self.name}-{self.sent}"}
        if params is not None:
            command["params"] = params
        for _attempt in range(TRIES):
            if self.engine is None:
                raise EegApiError(self.why_disconnected())
            self.log(f"-> {json.dumps(command)}")
            self._send(command, self.engine)
            deadline = time.monotonic() + REPLY_TIMEOUT_S
            while time.monotonic() < deadline:
                self.poll()
                if command["ref"] in self.replies:
                    reply = self.replies.pop(command["ref"])
                    self.log(f"<- {json.dumps(reply)}")
                    return reply
                if self.engine is None:
                    raise EegApiError(self.why_disconnected())
        raise EegApiError(f"{cmd}: no reply after {TRIES} tries")

    def start(self):
        """Sends the settings of config.json, then starts the mode. Raises EegApiError on a
        refusal (the reason is the engine's, in English)."""
        params = dict(self.config["params"])
        refresh = float(self.config["propose_refresh_hz"] or 0)
        if refresh > 0:
            proposed = self.send_command("propose_params", {"refresh_hz": refresh})
            if not proposed.get("accepted"):
                raise EegApiError(f"propose_params: {proposed.get('reason')}")
            params.update({"refresh_hz": refresh, proposed["key"]: proposed["value"]})
        if params:
            reply = self.send_command("set_params", params)
            if not reply.get("accepted"):
                raise EegApiError(f"set_params: {reply.get('reason')}")
        reply = self.send_command("start_mode")
        if not reply.get("accepted"):
            raise EegApiError(f"start_mode: {reply.get('reason')}")
        self.started_here = not reply.get("already_running")
        if reply.get("deferred"):
            self.log("This mode needs a model: in the console, choose it, then click "
                     "\"Start decoding\".")
        return reply

    # --- decisions -----------------------------------------------------------------------------

    def decisions(self, should_stop=lambda: False):
        """Yields every decision the engine pushes, as a dict {channel name: value} ("mode",
        then the channels of the mode's decoded stream: target_index, freq_hz… for SSVEP), -1
        included (-1 means "no decision", never target 0). Ends when the connection ends, or
        when should_stop() becomes true."""
        while self.engine is not None and not should_stop():
            self.poll()
            while self.queue:
                yield self.queue.pop(0)
        if self.engine is None:
            self.log(self.why_disconnected())

    # --- the end -------------------------------------------------------------------------------

    def close(self):
        """Stops the mode we started (if `stop_mode_on_exit`), says "bye" (the console ends the
        connection at once), then closes the socket."""
        try:
            if self.started_here and self.config["stop_mode_on_exit"] and self.engine:
                self.send_command("stop_mode")
        except EegApiError:
            pass
        self._send({"bye": True}, self.engine or self.announce_to)
        self.engine = None
        self.sock.close()

    # --- the network ---------------------------------------------------------------------------

    def poll(self):
        """One short turn (about 0.05 s): sends the hello or the alive that is due, reads what
        arrived, and notices a silent engine. Called by every other method."""
        now = time.monotonic()
        if self.engine is None and now >= self.next_hello:
            self.next_hello = now + HELLO_EVERY_S
            self._send({"hello": HELLO, "app": self.name, "id": self.ident, "port": self.port},
                       self.announce_to)
        if self.engine is not None and now >= self.next_alive:
            self.next_alive = now + ALIVE_EVERY_S
            self._send({"alive": True}, self.engine)
        for _ in range(100):
            try:
                data, source = self.sock.recvfrom(65536)
            except socket.timeout:
                break
            except ConnectionResetError:
                continue            # Windows: an earlier datagram reached a closed port
            except OSError:
                break
            self._received(data, source)
        if self.engine is not None and time.monotonic() - self.heard >= SILENCE_S:
            self.engine, self.ended = None, "silent"

    def _send(self, message, to):
        try:
            self.sock.sendto(json.dumps({"v": VERSION, **message}).encode("utf-8"), to)
        except OSError as e:        # no network, for example: keep going
            self.log(f"(cannot send to {to[0]}:{to[1]}: {e})")

    def _received(self, data, source):
        if len(data) > MAX_DATAGRAM:
            return
        try:
            message = json.loads(data.decode("utf-8"))
        except ValueError:
            return
        if not isinstance(message, dict) or message.get("v") != VERSION:
            return
        if message.get("identify") is True:
            self.on_identify()
            return
        if "connect" in message:
            if self.engine is not None and source != self.engine:
                self._send({"connected": False, "busy": self.console}, source)
                return
            self.engine, self.console = source, message.get("host")
            self.last_seq = 0       # a new connection: its "seq" starts again
            self.heard = self.next_alive = time.monotonic()
            self.ended, self.phase = None, None
            self._send({"connected": True}, source)
            return
        if source != self.engine:
            return                  # not from OUR engine
        self.heard = time.monotonic()
        if "alive" in message:
            return
        seq = message.get("seq")
        if isinstance(seq, int) and not isinstance(seq, bool):
            if seq <= self.last_seq:
                return              # older than the last one: UDP delivered it late
            self.last_seq = seq
        event = message.get("event")
        if event == "disconnected":
            self.engine, self.ended = None, message
        elif event == "failed":
            self.failures[message.get("ref")] = message
            self.log(f"<- {json.dumps(message)}")
        elif "status" in message:
            phase = (message["status"] or {}).get("phase")
            if phase != self.phase:
                self.phase = phase
                instruction = message["status"].get("instruction")
                self.log(f"status: {phase}" + (f" - {instruction}" if instruction else ""))
        elif "decision" in message:
            self.queue.append(message["decision"])
        elif "ref" in message:
            self.replies[message["ref"]] = message
