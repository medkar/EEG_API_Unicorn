"""ROS 2 node: connects to the EEG_API_Unicorn console over UDP, starts the mode set in
config/params.yaml, and publishes every decision as ROS topics. Do not edit this file: the
settings are in config/params.yaml.

Published topics (std_msgs only):

    eeg/decision    std_msgs/String    the whole decision, as JSON: {"mode": "ssvep",
                                       "target_index": 1.0, "freq_hz": 15.0, ...}
    eeg/target      std_msgs/Int32     target_index (SSVEP) or intent_index (MI); -1 = no
                                       decision, never target 0
    eeg/confidence  std_msgs/Float32   the score of the decision, on the stream's decision scale
    eeg/state       std_msgs/String    announcing, connected, decoding, disconnected, failed

The node publishes an INTENT ("target 1 is looked at"), never a robot command: turning it into a
motion is the job of another node (intent_to_twist is an example). The connection itself is the
library of clients/raspberry-pi (eeg_api_udp.py), unchanged.
"""

import json
import threading

import rclpy
from rclpy.node import Node
from std_msgs.msg import Float32, Int32, String

from eeg_api_ros.eeg_api_udp import EegApiDevice, EegApiError

try:                                    # ROS 2 Humble and later
    from rclpy.executors import ExternalShutdownException
except ImportError:                     # pragma: no cover - older distributions
    ExternalShutdownException = KeyboardInterrupt

PARAMETERS = {
    "app_name": "my-robot",
    "device_id": "",
    "device_port": 5011,
    "engine_host": "255.255.255.255",
    "engine_port": 5010,
    "mode": "ssvep",
    "settings": "{}",                   # the settings of the mode, as JSON (docs/control.md)
    "propose_refresh_hz": 0.0,
    "stop_mode_on_exit": True,
}


class Bridge(Node):
    def __init__(self):
        super().__init__("eeg_api_bridge")
        for name, default in PARAMETERS.items():
            self.declare_parameter(name, default)
        value = {name: self.get_parameter(name).value for name in PARAMETERS}
        config = {
            "app_name": value["app_name"],
            "device_id": value["device_id"],
            "device_port": int(value["device_port"]),
            "engine_host": value["engine_host"],
            "engine_port": int(value["engine_port"]),
            "mode": value["mode"],
            "params": json.loads(value["settings"] or "{}"),
            "propose_refresh_hz": float(value["propose_refresh_hz"]),
            "stop_mode_on_exit": bool(value["stop_mode_on_exit"]),
        }
        self.decision_pub = self.create_publisher(String, "eeg/decision", 10)
        self.target_pub = self.create_publisher(Int32, "eeg/target", 10)
        self.confidence_pub = self.create_publisher(Float32, "eeg/confidence", 10)
        self.state_pub = self.create_publisher(String, "eeg/state", 10)
        self.stopping = threading.Event()
        self.device = EegApiDevice(config, log=lambda m: self.get_logger().info(m))
        self.worker = threading.Thread(target=self.run, daemon=True)
        self.worker.start()

    def state(self, text):
        self.state_pub.publish(String(data=text))

    def run(self):
        """The device session, on its own thread: announce, start, publish, again after each
        disconnection, until the node stops."""
        stop = self.stopping.is_set
        while not stop():
            self.state("announcing")
            if not self.device.connect(should_stop=stop):
                return
            self.state("connected")
            try:
                self.device.start()
            except EegApiError as e:
                self.get_logger().error(str(e))
                self.state("failed")
                return
            self.state("decoding")
            for decision in self.device.decisions(should_stop=stop):
                self.publish(decision)
            if not stop():
                self.state("disconnected")

    def publish(self, decision):
        self.decision_pub.publish(String(data=json.dumps(decision)))
        index = decision.get("target_index", decision.get("intent_index"))
        if isinstance(index, (int, float)):
            self.target_pub.publish(Int32(data=int(index)))
        confidence = decision.get("confidence")
        if isinstance(confidence, (int, float)):
            self.confidence_pub.publish(Float32(data=float(confidence)))

    def shutdown(self):
        """Stops the session: the mode the device started is stopped, then "bye"."""
        self.stopping.set()
        self.worker.join(timeout=10.0)
        self.device.close()


def main(args=None):
    rclpy.init(args=args)
    node = Bridge()
    try:
        rclpy.spin(node)
    except (KeyboardInterrupt, ExternalShutdownException):
        pass
    finally:
        node.shutdown()
        node.destroy_node()
        if rclpy.ok():
            rclpy.shutdown()


if __name__ == "__main__":
    main()
