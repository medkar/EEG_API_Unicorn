using System;
using System.Collections.Generic;
using System.Globalization;
using System.Text;
using LSL;
using UnityEngine;

/// <summary>
/// The link between an application and the EEG_API_Unicorn engine, over LSL: the handshake, the
/// commands, the replies, the "disconnected" message. It is the C# counterpart of the
/// EngineLink class of examples/control_client.py, step for step (the contract is in
/// docs/control.md):
///
///     application --- EEG_API_Unicorn_control --->  engine    commands (WE create this stream)
///     application <-- EEG_API_Unicorn_replies ----  engine    one reply per command
///
/// Every call BLOCKS (it waits for LSL): run it on a worker thread, never in Update().
/// EegApiClient does exactly that. Requires the LSL C# binding (LSL.cs) and the native library
/// (lsl.dll) in the project: see clients/unity/README.md. Do not edit this file.
/// </summary>
public class EegApiLink : IDisposable
{
    public const string ControlStream = "EEG_API_Unicorn_control";
    public const string RepliesStream = "EEG_API_Unicorn_replies";
    /// <summary>Every stream of the engine starts with it: "EEG_API_Unicorn_decoded_ssvep"…</summary>
    public const string StreamPrefix = "EEG_API_Unicorn_";

    /// <summary>A reply that has not arrived after this long will not arrive: send again.</summary>
    public const double ReplyTimeoutS = 5.0;

    /// <summary>
    /// The source_id of our command stream: the name the console lists under "Connect an
    /// application". A random part makes it unique, so that two copies of the application (on
    /// one computer or on several) never take each other's replies.
    /// </summary>
    public readonly string Name;

    /// <summary>The engine that answered us first; we only listen to it afterwards.</summary>
    public string EngineId { get; private set; }

    /// <summary>The engine's "disconnected" message meant for us, or null while connected.</summary>
    public EngineReply Disconnection { get; private set; }

    readonly string refPrefix;
    readonly Action<string> log;
    readonly StreamOutlet outlet;
    readonly List<KeyValuePair<StreamInlet, string>> replies = new List<KeyValuePair<StreamInlet, string>>();
    readonly List<EngineReply> inbox = new List<EngineReply>();
    readonly string[] sample = new string[1];
    int sent;
    bool warned;

    public EegApiLink(string appName, Action<string> log)
    {
        this.log = log ?? (_ => { });
        Name = appName + "-" + Guid.NewGuid().ToString("N").Substring(0, 6);
        refPrefix = Name + "-";
        // The command stream: type Markers, 1 channel, one JSON string per sample. LSL cannot
        // receive on a stream it publishes: that is why WE create it, and the engine reads it.
        var info = new StreamInfo(ControlStream, "Markers", 1, LSL.LSL.IRREGULAR_RATE,
                                  channel_format_t.cf_string, Name);
        outlet = new StreamOutlet(info);
    }

    /// <summary>
    /// Opens the reply streams of the network, then waits until the engine reads our command
    /// stream: with the console, until someone clicks "Connect an application", picks us, then
    /// "Connect". False when no engine runs (after timeoutS) or when cancelled() becomes true.
    /// </summary>
    public bool Connect(double timeoutS, Func<bool> cancelled)
    {
        DateTime deadline = DateTime.UtcNow.AddSeconds(timeoutS);
        while (replies.Count == 0 && DateTime.UtcNow < deadline && !cancelled())
        {
            // `minimum` is a number never reached: the call waits the whole second and returns
            // EVERY reply stream that answered (there may be several engines on the network).
            foreach (StreamInfo found in LSL.LSL.resolve_stream("name", RepliesStream, 1000, 1.0))
            {
                var inlet = new StreamInlet(found);
                try
                {
                    // Trap 2: listen BEFORE the first command, or its reply is lost.
                    inlet.open_stream(2.0);
                }
                catch (Exception)
                {
                    inlet.Dispose();    // an engine that has just quit: skip it
                    continue;
                }
                replies.Add(new KeyValuePair<StreamInlet, string>(inlet, EngineIdOf(found.source_id())));
            }
        }
        if (replies.Count == 0)
            return false;
        // Trap 1: a command pushed before the engine reads our stream is LOST. With the console,
        // the engine reads it only once someone has connected us: wait as long as it takes, and
        // say what we are waiting for. Short slices (1 s), so that cancelled() is seen quickly.
        int slices = 0;
        while (!outlet.wait_for_consumers(1.0))
        {
            if (cancelled())
                return false;
            if (slices % 10 == 0)
                log("Waiting to be connected: in the console, click \"Connect an application\", " +
                    "pick '" + Name + "', then \"Connect\".");
            slices++;
        }
        return true;
    }

    /// <summary>
    /// Still connected? False as soon as the engine has said it stopped reading our command
    /// stream. Do not rely on have_consumers() alone: it stays true until our next push.
    /// </summary>
    public bool Connected()
    {
        Poll();
        if (Disconnection != null)
            return false;
        return outlet.have_consumers();
    }

    /// <summary>Reads every reply waiting on the reply streams, and keeps those meant for us.</summary>
    public void Poll()
    {
        foreach (KeyValuePair<StreamInlet, string> pair in replies)
        {
            while (true)
            {
                double timestamp;
                try
                {
                    timestamp = pair.Key.pull_sample(sample, 0.0);
                }
                catch (LostException)
                {
                    break;              // that engine has gone: its stream is closed
                }
                if (timestamp == 0.0)
                    break;              // nothing more for now
                EngineReply reply = Parse(sample[0]);
                if (reply == null)
                    continue;
                if (reply.@event == "disconnected")
                {
                    // Not a reply: its "ref" is null. The reply stream is shared, so the message
                    // is ours only if "app" is OUR source_id, and if it comes from OUR engine.
                    bool fromOurEngine = EngineId == null || pair.Value == EngineId;
                    if (reply.app == Name && fromOurEngine && Disconnection == null)
                    {
                        Disconnection = reply;
                        log("<- " + sample[0]);
                    }
                    continue;
                }
                if (reply.@ref == null || !reply.@ref.StartsWith(refPrefix, StringComparison.Ordinal))
                    continue;           // a reply to ANOTHER application
                if (EngineId == null)
                    EngineId = pair.Value;
                if (pair.Value != EngineId)
                {
                    if (!warned)
                    {
                        warned = true;
                        log("WARNING: engine '" + pair.Value + "' answers too; only one engine " +
                            "should read our commands. Keeping '" + EngineId + "'.");
                    }
                    continue;
                }
                inbox.Add(reply);
            }
        }
    }

    /// <summary>
    /// Sends one command and returns ITS reply, or null: after ReplyTimeoutS (the command or
    /// its reply was lost: send it again, it is safe), or at once if we are disconnected.
    /// `parametersJson` is the JSON object of the settings, or null (see Json below).
    /// </summary>
    public EngineReply Send(string cmd, string mode, string parametersJson = null)
    {
        if (!Connected())
            return null;
        sent++;
        string reference = refPrefix + sent;
        string text = "{\"cmd\": " + Json.Text(cmd) + ", \"mode\": " + Json.Text(mode) +
                      (parametersJson != null ? ", \"params\": " + parametersJson : "") +
                      ", \"ref\": " + Json.Text(reference) + "}";
        log("-> " + text);
        outlet.push_sample(new[] { text });
        DateTime deadline = DateTime.UtcNow.AddSeconds(ReplyTimeoutS);
        while (DateTime.UtcNow < deadline)
        {
            bool connected = Connected();       // reads the waiting replies too
            foreach (EngineReply reply in inbox)
            {
                // A message with "event" is not the reply: it comes LATER (see Failure).
                if (reply.@ref == reference && string.IsNullOrEmpty(reply.@event))
                {
                    log("<- " + reply.text);
                    return reply;
                }
            }
            if (!connected)
                return null;
            System.Threading.Thread.Sleep(20);
        }
        log("(no reply after " + ReplyTimeoutS + " s: the command or its reply was lost)");
        return null;
    }

    /// <summary>
    /// The second message of an ACCEPTED command that failed later in the engine (for example a
    /// model file that cannot be loaded), or null. Without it, an application would wait forever.
    /// </summary>
    public EngineReply Failure(string reference)
    {
        Poll();
        return inbox.Find(r => r.@ref == reference && r.@event == "failed");
    }

    /// <summary>
    /// Opens the decoded stream of a mode, on OUR engine: every engine publishes under the same
    /// name, and the source_id ("name@engine id") tells them apart. Waits, with no time limit,
    /// while the mode is not running yet (a mode with a model waits for the person to choose
    /// it in the console). Null when we are disconnected or when cancelled() becomes true.
    /// `labels` receives the channel names of the stream ("target_index", "freq_hz"…).
    /// </summary>
    public StreamInlet OpenDecoded(string mode, Func<bool> cancelled, out string[] labels)
    {
        labels = new string[0];
        string sourceId = StreamPrefix + "decoded_" + mode + "@" + EngineId;
        while (!cancelled())
        {
            if (!Connected())
                return null;
            foreach (StreamInfo found in LSL.LSL.resolve_stream("source_id", sourceId, 1, 0.5))
            {
                var inlet = new StreamInlet(found);
                try
                {
                    inlet.open_stream(1.0);
                    labels = ChannelLabels(inlet.info(2.0));
                    return inlet;
                }
                catch (Exception)
                {
                    inlet.Dispose();    // the stream vanished meanwhile: look again
                }
            }
        }
        return null;
    }

    /// <summary>The channel names written in a stream's description (desc/channels/channel/label).</summary>
    static string[] ChannelLabels(StreamInfo info)
    {
        var labels = new List<string>();
        XMLElement channel = info.desc().child("channels").child("channel");
        while (!channel.empty())
        {
            labels.Add(channel.child_value("label"));
            channel = channel.next_sibling();
        }
        for (int i = labels.Count; i < info.channel_count(); i++)
            labels.Add("ch" + i);
        return labels.ToArray();
    }

    /// <summary>Why the link ended, in plain words, once Connected() is false.</summary>
    public string WhyDisconnected()
    {
        if (Disconnection == null)
            return "no engine reads our commands any more (it may have crashed)";
        if (Disconnection.cause == "console")
            return "disconnected in the console: the engine stopped what we started";
        if (Disconnection.cause == "engine_stopped")
            return "the engine stopped (the console closed, or server.py stopped)";
        return "disconnected: " + Disconnection.reason;
    }

    public void Dispose()
    {
        foreach (KeyValuePair<StreamInlet, string> pair in replies)
            pair.Key.Dispose();
        replies.Clear();
        outlet.Dispose();
    }

    /// <summary>The engine id in a source_id: "EEG_API_Unicorn_replies@my-pc" -> "my-pc".</summary>
    static string EngineIdOf(string sourceId)
    {
        int at = sourceId.IndexOf('@');
        return at < 0 ? "" : sourceId.Substring(at + 1);
    }

    static EngineReply Parse(string text)
    {
        try
        {
            EngineReply reply = JsonUtility.FromJson<EngineReply>(text);
            if (reply != null)
                reply.text = text;
            return reply;
        }
        catch (Exception)
        {
            return null;        // not JSON: ignored
        }
    }
}

/// <summary>
/// The fields of a reply this example reads (the full list is in docs/control.md). JsonUtility
/// fills the fields present in the JSON and leaves the others at their default value; "params"
/// is not read here. `@ref` and `@event` are the JSON fields "ref" and "event" (C# keywords).
/// </summary>
[Serializable]
public class EngineReply
{
    public string @ref;
    public string cmd;
    public string mode;
    public bool accepted;
    public bool deferred;
    public bool already_running;
    public bool already_stopped;
    public string reason;
    public string warning;
    public string @event;
    public string cause;
    public string app;
    public string[] stopped;
    public string key;
    // propose_params: the proposed frequencies, for SSVEP. In double, as sent: a float would turn
    // 8.571428571 Hz (60 / 7) into 8.5714293 Hz, which no longer divides the screen's 60 Hz.
    public double[] value;
    [NonSerialized] public string text;
}

/// <summary>The few JSON values this example writes: a text, a number, a list of numbers.</summary>
public static class Json
{
    public static string Text(string s)
    {
        var b = new StringBuilder("\"");
        foreach (char c in s)
        {
            if (c == '"' || c == '\\') b.Append('\\').Append(c);
            else if (c < ' ') b.Append("\\u").Append(((int)c).ToString("x4"));
            else b.Append(c);
        }
        return b.Append('"').ToString();
    }

    // Always a dot as the decimal separator, whatever the language of the computer.
    public static string Number(double x) => x.ToString("R", CultureInfo.InvariantCulture);

    public static string Numbers(double[] xs)
    {
        var parts = new string[xs.Length];
        for (int i = 0; i < xs.Length; i++)
            parts[i] = Number(xs[i]);
        return "[" + string.Join(", ", parts) + "]";
    }
}
